#!/usr/bin/env python3
"""Rebuild the current Limine ISO filesystem without obsolete overlay sessions."""
import argparse
import fcntl
import json
from pathlib import Path
import shutil
import subprocess

from source_tree import digest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--iso', type=Path, required=True)
    parser.add_argument('--output-root', type=Path, required=True)
    parser.add_argument('--limine-dir', type=Path, required=True,
                        help='source-built host Limine programs and firmware')
    parser.add_argument('--keep-root', action='store_true', help='retain the extracted filesystem for inspection')
    args = parser.parse_args()
    image = args.iso.resolve(strict=True)
    boot = args.limine_dir.resolve(strict=True)
    for name in ('limine', 'BOOTX64.EFI', 'limine-bios.sys', 'limine-bios-cd.bin', 'limine-uefi-cd.bin'):
        (boot / name).resolve(strict=True)
    out = args.output_root.resolve()
    out.mkdir(parents=True, exist_ok=False)
    root = out / 'root'
    root.mkdir()
    result = out / image.name
    with Path(str(image) + '.lock').open('a') as lock, (out / 'image.log').open('w') as log:
        fcntl.flock(lock, fcntl.LOCK_SH | fcntl.LOCK_NB)
        before = digest(image)

        def run(command):
            subprocess.run(list(map(str, command)), check=True, stdout=log, stderr=subprocess.STDOUT)

        run(['xorriso', '-no_rc', '-osirrox', 'on', '-indev', image, '-extract', '/', root])
        if not (root / 'boot/limine/limine.conf').is_file():
            raise ValueError('Expected an existing Limine ISO')
        payload = {str(p.relative_to(root)): digest(p) for p in sorted(root.rglob('*')) if p.is_file()}
        for name, relative in [('BOOTX64.EFI', 'EFI/BOOT/BOOTX64.EFI'),
                               *[(n, 'boot/limine/' + n) for n in
                                 ('limine-bios.sys', 'limine-bios-cd.bin', 'limine-uefi-cd.bin')]]:
            (root / relative).write_bytes((boot / name).read_bytes())
        run(['xorriso', '-as', 'mkisofs', '-R', '-J', '-V', 'COAST_ISO',
             '-b', 'boot/limine/limine-bios-cd.bin', '-no-emul-boot', '-boot-load-size', '4',
             '-boot-info-table', '--efi-boot', 'boot/limine/limine-uefi-cd.bin',
             '-efi-boot-part', '--efi-boot-image', '--protective-msdos-label', root, '-o', result])
        run([boot / 'limine', 'bios-install', result])
        if digest(image) != before:
            raise ValueError('Input ISO changed during compaction')
        # Verify actual file bytes read back from the resulting filesystem.
        # El Torito's catalog and BIOS boot-info table are regenerated by mkisofs.
        verified = out / 'verified'
        verified.mkdir()
        run(['xorriso', '-no_rc', '-osirrox', 'on', '-indev', result, '-extract', '/', verified])
        updated = {str(p.relative_to(root)): digest(p) for p in sorted(root.rglob('*')) if p.is_file()}
        actual = {str(p.relative_to(verified)): digest(p) for p in sorted(verified.rglob('*')) if p.is_file()}
        if actual.keys() != updated.keys() or any(actual[p] != sha for p, sha in updated.items()
                                                 if p not in ('boot.catalog', 'boot/limine/limine-bios-cd.bin')):
            raise ValueError('Compacted ISO payload mismatch')
        record = dict(iso=str(result), iso_sha256=digest(result), input_iso=str(image),
                      input_iso_sha256=before, input_bytes=image.stat().st_size,
                      bytes=result.stat().st_size, guest_verification_pending=True,
                      changed_files=[p for p in updated if updated[p] != payload.get(p)],
                      files=actual, target_host_executed=False)
        original_manifest = image.parent / 'MANIFEST.json'
        if original_manifest.is_file():
            record['input_manifest_sha256'] = digest(original_manifest)
            record['diagnostics_qa_only'] = json.loads(original_manifest.read_text()).get('diagnostics_qa_only', False)
        (out / 'MANIFEST.json').write_text(json.dumps(record, indent=2) + '\n')
        shutil.rmtree(verified)
        if not args.keep_root:
            shutil.rmtree(root)
        print(json.dumps({k: v for k, v in record.items() if k != 'files'}, indent=2))


if __name__ == '__main__':
    main()
