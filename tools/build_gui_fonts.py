#!/usr/bin/env python3
"""Optional regeneration of the embedded, antialiased desktop glyph atlas.

The committed atlas is sufficient to build the OS; Pillow and host fonts are
only needed to regenerate it. DejaVu licensing is in desktop/assets/.
"""
from pathlib import Path
import argparse
from PIL import Image, ImageDraw, ImageFont

p = argparse.ArgumentParser()
p.add_argument('--fonts', type=Path, default=Path('/usr/share/fonts/TTF'))
a = p.parse_args()

root = Path(__file__).resolve().parents[1]
faces = [('DejaVuSans.ttf', 9), ('DejaVuSans.ttf', 10), ('DejaVuSans-Bold.ttf', 10),
         ('DejaVuSans.ttf', 11), ('DejaVuSans-Bold.ttf', 11), ('DejaVuSans-Bold.ttf', 20),
         ('DejaVuSansMono.ttf', 11), ('DejaVuSansMono.ttf', 13)]
pixels, glyphs, metrics = bytearray(), [], []
for scale in [100, 125, 150, 200]:
    for filename, size in faces:
        font = ImageFont.truetype(str(a.fonts / filename), round(size * scale / 100))
        asc, desc = font.getmetrics()
        metrics.append((asc, asc + desc))

        for code in range(32, 256):
            c = chr(code) if code < 127 or code >= 160 else '?'
            box = font.getbbox(c)
            w, h = box[2] - box[0], box[3] - box[1]
            im = Image.new('L', (max(w, 1), max(h, 1)))
            ImageDraw.Draw(im).text((-box[0], -box[1]), c, font=font, fill=255)
            glyphs.append((len(pixels), w, h, box[0], box[1], round(font.getlength(c) * 64)))
            pixels.extend(im.crop((0, 0, w, h)).tobytes())

header = '''/* Generated by tools/build_gui_fonts.py. DejaVu font license in assets/. */
#ifndef DESKTOP_FONT_DATA_H
#define DESKTOP_FONT_DATA_H
#include <stdint.h>
struct Glyph { uint32_t offset; uint8_t w,h; int8_t left,top; uint16_t advance; };
extern const struct Glyph gui_glyphs[32][224];
extern const uint8_t gui_font_metrics[32][2];
extern const uint8_t gui_font_pixels[];
#endif
'''
(root / 'userland/desktop/font_data.h').write_text(header)
out = ['#include "font_data.h"\nconst uint8_t gui_font_metrics[32][2]={',
       ','.join('{%d,%d}' % m for m in metrics), '};\nconst struct Glyph gui_glyphs[32][224]={']
for i in range(32):
    out.append('{' + ','.join('{%d,%d,%d,%d,%d,%d}' %
               g for g in glyphs[i * 224:(i + 1) * 224]) + '},')
out.append('};\nconst uint8_t gui_font_pixels[]={')
for i in range(0, len(pixels), 32):
    out.append(','.join(str(n) for n in pixels[i:i + 32]) + ',')
out.append('};\n')
(root / 'userland/desktop/font_data.c').write_text('\n'.join(out))

print(f'Embedded {len(pixels):,} glyph bytes for four scales, eight font styles.')
